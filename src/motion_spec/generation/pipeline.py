from __future__ import annotations

import json
import os
import shutil
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING
from uuid import uuid4

import rdflib
from rdflib import URIRef
from rdflib.namespace import PROV, RDF

from motion_spec.setup import BUILD_TYPE, BUILD_TYPE_VARIABLE, build_jobs
from motion_spec.utils import LOG_DIRECTORY, tee

if TYPE_CHECKING:
    from motion_spec.rdf_parser.model import Model


@dataclass
class LoadedModel:
    """A model as generation loads it, in memory: the DSL's dataset joined with the scene and
    FSM graphs and the bundles scene-dsl and coord-dsl recorded them in, read as a `Model`, and
    coord-dsl's framed FSM."""

    dataset: rdflib.Dataset
    model: Model
    document: Path
    fsm: dict | None
    # (source file, document, graph IRI) per imported scene or FSM
    imports: list[tuple[Path, object, URIRef]]
    # package -> (bundle, agent): scene-dsl's PackageInfo, coord-dsl's purl
    bundles: dict[str, tuple[URIRef, object]]


def new_id(name: str) -> str:
    """Return a time-ordered identifier unique to one generation or run."""
    return f"{name}-{datetime.now(UTC).strftime('%Y%m%dT%H%M%S%fZ')}"


def create_generation_dir(
    model: Path, output_dir: Path | None = None, name: str | None = None
) -> Path:
    """Create <base>/<name>/<timestamp> for MODEL, where base is OUTPUT_DIR or ./generation.

    NAME defaults to the model's own stem; one model generated several ways names each tree
    for what tells them apart.
    """
    base = output_dir or Path.cwd() / "generation"
    generation = base / (name or model.stem) / datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")
    generation.mkdir(parents=True, exist_ok=False)
    generation = generation.resolve()
    from motion_spec.config import CONFIG_FILE, find_config

    # the generation's workspace config first; the cwd may be elsewhere
    path = find_config(generation) or find_config()
    if path is not None:
        shutil.copy2(path, generation / CONFIG_FILE)
    return generation


def load_model(model: Path, model_dir: Path) -> LoadedModel:
    """MODEL parsed, generated by the DSL into MODEL_DIR, and joined with its scene and FSM graphs,
    each a named graph that scene-dsl or coord-dsl built and recorded in its own bundle."""
    from coord_dsl.generators.fsm import gen_json
    from coord_dsl.rdf.provenance import build, create_coord_dsl_bundle
    from coord_dsl.rdf.vocab import URI_FSM_TYPE_FSM
    from motion_spec_dsl.gens import generate
    from rdf_utils import DatasetFormat
    from rdf_utils.models.prov import create_pkg_bundle
    from rdf_utils.models.textx import record_model_to_graph
    from rdf_utils.naming import get_valid_var_name
    from scene_dsl.rdf.scenex import create_scenex_model_graph
    from textx import metamodel_for_file
    from textx.exceptions import TextXError

    from motion_spec.rdf_parser.model import Model

    document = model_dir / f"{model.stem}.{DatasetFormat.JSON_LD.extension}"
    try:
        authored = metamodel_for_file(str(model)).model_from_file(str(model))
        dataset = generate(authored, document)
    except TextXError as problem:
        raise RuntimeError(f"the DSL rejected {model.name}: {problem}") from problem
    imports, fsms, scene_headers, bundles = [], [], {}, {}
    for imported in authored.imports:
        for loaded_document in imported._tx_loaded_models:
            source = Path(loaded_document._tx_filename).resolve()
            if source.suffix == ".scenex":
                if "scene_dsl" not in bundles:
                    bundles["scene_dsl"] = create_pkg_bundle(dataset, "scene_dsl")
                bundle_id, info = bundles["scene_dsl"]
                graph_id = record_model_to_graph(
                    loaded_document, dataset, bundle_id, info.purl, create_scenex_model_graph
                )
                # named as scene-dsl's generator names them
                namespace = get_valid_var_name(source.stem or "scene")
                namespace = f"scene_{namespace}" if namespace[0].isdigit() else namespace
                scene_headers[graph_id] = (f"{source.stem}.kdl.hpp", namespace)
            elif source.suffix == ".fsm":
                if "coord_dsl" not in bundles:
                    bundles["coord_dsl"] = create_coord_dsl_bundle(dataset)
                bundle_id, agent = bundles["coord_dsl"]
                graph_id = build(loaded_document, dataset, bundle_id, agent)
                fsms.append((loaded_document, graph_id))
            else:
                continue
            imports.append((source, loaded_document, graph_id))
    if len(fsms) > 1:
        raise RuntimeError(f"{model.name} imports {len(fsms)} FSMs; the program runs one")
    fsm = None
    if fsms:
        fsm_document, graph_id = fsms[0]
        fsm_graph = dataset.graph(graph_id)
        fsm_ref = fsm_graph.value(predicate=RDF.type, object=URI_FSM_TYPE_FSM)
        fsm = {**gen_json(fsm_graph, fsm_ref), "namespace_uri": fsm_document.fsm.ns.uri}
    loaded = Model(
        graph=dataset,
        namespaces=tuple(namespace.uri for namespace in authored.namespaces),
        scene_headers=scene_headers,
    )
    return LoadedModel(dataset, loaded, document, fsm, imports, bundles)


def generate_model(
    model: Path, generation: Path, *, stage: str = "code", env: dict[str, str] | None = None
) -> Path:
    """Generate MODEL through IR or C++ code and return its generated-artifact directory.

    ENV is the environment the caller resolved; codegen looks for `stst` along its PATH, so a
    workspace tool is found rather than whatever this process happens to have first.
    """
    from coord_dsl.rdf.provenance import render
    from motion_spec_dsl.rdf_parser.check import validate_dataset
    from rdf_utils import DatasetFormat
    from rdf_utils.models.prov import (
        add_activity,
        add_agent,
        add_directory_location,
        add_entity,
        capture_file_prov,
        create_bundle,
        get_file_path,
        get_py_pkg_info,
        load_transformation_prov,
        record_graph_to_text,
    )
    from rdf_utils.models.time import add_wall_instant
    from scene_dsl import gens as scene_gens

    from motion_spec.classes.base import DataclassJSONEncoder
    from motion_spec.rdf_parser.ir import generate_ir
    from motion_spec.runs.provenance import (
        DERIVED_DOCUMENT,
        GENERATION_DOCUMENT,
        add_delegation,
        add_package,
        build_derivation_document,
        record_code_generation,
        record_ir_generation,
    )

    generated = generation / "generated"
    model_dir = generated / "model"
    generation_activity = URIRef(uuid4().urn)
    generation_started = datetime.now(UTC)
    loaded = load_model(model, model_dir)
    dataset, fsm = loaded.dataset, loaded.fsm
    motion_spec = get_py_pkg_info("motion_spec").purl
    record = dataset.graph(create_bundle(dataset, motion_spec))
    roots = {generation.resolve(): add_directory_location(record, generation)}
    dsl = get_py_pkg_info("motion_spec_dsl").purl
    source_dir = generated / "source"
    source_dir.mkdir(parents=True)
    originals = set()
    for bundle in dataset.graphs():
        if (bundle.identifier, RDF.type, PROV.Bundle) not in bundle:
            continue
        for original in set(bundle.objects(None, PROV.used)):
            path = get_file_path(bundle, original)
            if path is None or not path.is_file():
                continue
            kept = source_dir / path.name
            if kept.exists() and kept.read_bytes() != path.read_bytes():
                raise RuntimeError(f"generated source-name collision: {path.name}")
            shutil.copy2(path, kept)
            add_entity(record, original)
            originals.add(original)
            copy = capture_file_prov(record, kept, roots=roots)
            record.add((copy, PROV.wasGeneratedBy, generation_activity))
            record.add((copy, PROV.alternateOf, original))
    graph_files = {capture_file_prov(record, loaded.document, roots=roots): dsl}
    started = datetime.now(UTC)
    written = {}
    for source, _document, graph_id in loaded.imports:
        path = model_dir / f"{source.name}.ld.json"
        document_graphs = rdflib.Dataset()
        document_graphs.add_graph(dataset.graph(graph_id))
        document_graphs.serialize(destination=path, format="json-ld")
        written[graph_id] = capture_file_prov(record, path, roots=roots)
    if written:
        load_transformation_prov(
            record,
            set(written),
            set(written.values()),
            add_package(record, "motion_spec"),
            started=started,
            ended=datetime.now(UTC),
        )
        graph_files.update(dict.fromkeys(written.values(), motion_spec))
    conforms, report = validate_dataset(dataset)
    if not conforms:
        raise RuntimeError(f"generated RDF failed SHACL validation:\n{report}")
    ir_path = model_dir / "ir.json"
    started = datetime.now(UTC)
    ir_text = json.dumps(generate_ir(loaded.model, fsm), cls=DataclassJSONEncoder, indent=4)
    ir_path.write_text(ir_text)
    ir = json.loads(ir_text)
    derived_path = generated / DERIVED_DOCUMENT
    derived_path.parent.mkdir(parents=True, exist_ok=True)
    authored = [
        graph
        for graph in dataset.graphs()
        if graph.identifier != loaded.model.derived.identifier
        and (None, RDF.type, PROV.Bundle) not in graph
    ]
    activity = URIRef(uuid4().urn)
    derived_path.write_text(
        build_derivation_document(ir, loaded.model.derived, authored, activity).serialize(
            format=DatasetFormat.JSON_LD, indent=2, auto_compact=True
        )
    )
    ir_entity = record_ir_generation(
        record,
        generation,
        graph_files,
        activity,
        ir,
        ir_path,
        derived_path,
        started=started,
        ended=datetime.now(UTC),
    )
    if stage == "code":
        from motion_spec.generation.codegen import generate_code
        from motion_spec.setup import find_stst

        controller_dir = generated / "controller"
        controller_dir.mkdir()
        started = datetime.now(UTC)
        stst = find_stst((env or {}).get("PATH")) or "stst"
        written_code = generate_code(
            ir_path, controller_dir, generated / "contract", stst, fsm, generation.parent.name
        )
        record_code_generation(
            record,
            generation,
            [
                ir_entity,
                *(
                    written[graph_id]
                    for source, _, graph_id in loaded.imports
                    if source.suffix == ".fsm"
                ),
            ],
            written_code,
            started=started,
            ended=datetime.now(UTC),
        )
        for source, _document, graph_id in loaded.imports:
            if source.suffix == ".scenex":
                bundle_id, info = loaded.bundles["scene_dsl"]
                header, namespace = loaded.model.scene_headers[graph_id]
                record_graph_to_text(
                    dataset,
                    graph_id,
                    bundle_id,
                    info,
                    lambda graph, namespace=namespace, name=source.name: scene_gens.kdl_header(
                        graph, namespace, name
                    ),
                    controller_dir / "headers" / header,
                    source_files=[Path(scene_gens.__file__).parent / scene_gens.KDL_TEMPLATE],
                )
            else:
                bundle_id, agent = loaded.bundles["coord_dsl"]
                render(
                    dataset, graph_id, bundle_id, agent, "cpp", controller_dir / f"{fsm['name']}.hpp"
                )
    add_activity(
        record,
        generation_activity,
        (),
        originals,
        motion_spec,
        add_wall_instant(record, generation_started),
        add_wall_instant(record, datetime.now(UTC)),
    )
    for key in ("motion_spec_dsl", *loaded.bundles):
        tool = get_py_pkg_info(key).purl
        add_agent(record, tool, (PROV.SoftwareAgent,), key)
        add_delegation(record, tool, motion_spec, generation_activity)
    # the DSL's bundle stays in the DSL's document
    document = rdflib.Dataset()
    for graph in dataset.graphs():
        if (graph.identifier, RDF.type, PROV.Bundle) in graph and (
            graph.identifier,
            PROV.wasAttributedTo,
            dsl,
        ) not in graph:
            document.add_graph(graph)
    (generated / GENERATION_DOCUMENT).write_text(
        document.serialize(format=DatasetFormat.JSON_LD, indent=2, auto_compact=True)
    )
    return generated


def build_generation(
    generation: Path,
    *,
    prefixes: tuple[Path, ...] = (),
    jobs: int | None = None,
    env: dict[str, str] | None = None,
) -> Path:
    """Configure and build GENERATION, returning the controller executable.

    ENV is what both cmake invocations run under; None inherits this process's.
    """
    controller = generation / "generated" / "controller"
    if not (controller / "CMakeLists.txt").is_file():
        raise RuntimeError(f"generated CMake project not found: {controller}")
    build = generation / "build"
    configure = [
        "cmake",
        "-S",
        str(controller),
        "-B",
        str(build),
        # CMake's default is no build type, i.e. unoptimized
        f"-DCMAKE_BUILD_TYPE={(env or os.environ).get(BUILD_TYPE_VARIABLE, BUILD_TYPE)}",
    ]
    if prefixes:
        configure.append(
            f"-DCMAKE_PREFIX_PATH={';'.join(str(path.resolve()) for path in prefixes)}"
        )
    from motion_spec.runs.provenance import record_build

    log = generation / LOG_DIRECTORY / "console.log"
    started = datetime.now(UTC)
    tee(configure, log=log, env=env)
    tee(["cmake", "--build", str(build), "--parallel", str(build_jobs(jobs))], log=log, env=env)
    executable = build / generation.parent.name
    if not executable.is_file():
        raise RuntimeError(f"controller executable not found after build: {executable}")
    record_build(
        generation / "generated", controller, executable, started=started, ended=datetime.now(UTC)
    )
    return executable
